const LANG_KEY = "otdoner_lang";

function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === "kz" || saved === "ru" || saved === "en") return saved;
  } catch (e) {}
  return "kz";
}

let LANG = getLang();

function t(key) {
  return (I18N[LANG] && I18N[LANG][key]) || (LANG === "en" && I18N.ru[key]) || I18N.kz[key] || key;
}

// data.js-тағы {kz, ru} объектісінен мәтін алу
function tr(obj) {
  if (!obj) return "";
  return obj[LANG] || (LANG === "en" && obj.ru) || obj.kz || "";
}

function applyI18n(root = document) {
  document.documentElement.lang = { kz: "kk", ru: "ru", en: "en" }[LANG] || "kk";
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  const title = document.querySelector("title[data-i18n-title]");
  if (title) title.textContent = t(title.dataset.i18nTitle);
  document.querySelectorAll(".lang__btn").forEach((b) => {
    b.setAttribute("aria-pressed", String(b.dataset.lang === LANG));
  });
}

function setLang(lang) {
  LANG = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) {}
  applyI18n();
  document.dispatchEvent(new CustomEvent("langchange"));
}

function formatPrice(n) {
  // мыңдықтар арасы мен ₸ алдында бөлінбейтін бос орын — баға екі жолға бөлінбейді
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ") + " ₸";
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang__btn").forEach((b) => {
    b.addEventListener("click", () => setLang(b.dataset.lang));
  });
  applyI18n();
});
